TemplateCategory categoryById(String id) => templateCategories.firstWhere(
  (c) => c.id == id,
  orElse: () => const TemplateCategory(
    'custom',
    'My templates',
    Icons.bookmark_rounded,
    OmniDesignTokens.primary,
    projectCategory: '',
  ),
);

PlanTemplate _t(
  String id,
  String name,
  String category,
  String description,
  String icon,
  Map<String, List<String>> sections, {
  Map<String, int> milestones = const {},
  int? days,
  List<String> keywords = const [],
}) {
  final cat = categoryById(category);
  return PlanTemplate(
    id: id,
    name: name,
    categoryId: category,
    description: description,
    icon: planIcon(icon),
    projectIcon: icon,
    color: cat.color,
    durationDays: days,
    keywords: keywords,
    sections: [
      for (final e in sections.entries)
        TemplateSection(e.key, [for (final s in e.value) TemplateTask.parse(s)]),
    ],
    milestones: [
      for (final e in milestones.entries) TemplateMilestone(e.key, e.value),
    ],
  );
}

